// Pure state transitions. Every function returns the same object reference
// when nothing changed, so callers can skip redundant storage writes.
import { normalizeUrl } from './url';
import {
  GLOBAL_NOTE_ID,
  SCHEMA_VERSION,
  type AppState,
  type ArchiveReason,
  type Note,
  type Settings,
  type TabInfo,
  type Task,
} from './types';

export const DETACH_GRACE_MS = 2 * 60 * 1000;
export const MAX_TASK_LENGTH = 1000;
export const MAX_TITLE_LENGTH = 200;

export const DEFAULT_SETTINGS: Settings = { switchTabs: false };

// ---------------------------------------------------------------- creation

export function createGlobalNote(now: number): Note {
  return {
    id: GLOBAL_NOTE_ID,
    kind: 'global',
    title: 'Global',
    originalUrl: '',
    url: '',
    tabId: null,
    windowId: null,
    tasks: [],
    status: 'active',
    createdAt: now,
    updatedAt: now,
    archivedAt: null,
    archiveReason: null,
    detachedAt: null,
  };
}

export function createInitialState(now: number): AppState {
  return {
    version: SCHEMA_VERSION,
    rev: 0,
    notes: { [GLOBAL_NOTE_ID]: createGlobalNote(now) },
    settings: { ...DEFAULT_SETTINGS },
  };
}

const str = (v: unknown, fallback: string, max: number) => (typeof v === 'string' ? v.slice(0, max) : fallback);
const num = (v: unknown, fallback: number) => (typeof v === 'number' && Number.isFinite(v) ? v : fallback);
const numOrNull = (v: unknown) => (typeof v === 'number' && Number.isFinite(v) ? v : null);
const ARCHIVE_REASONS: ArchiveReason[] = ['tab-closed', 'window-closed', 'session-lost'];
const MAX_URL_LENGTH = 8192;
const ID_PATTERN = /^[A-Za-z0-9_-]{1,128}$/;
const RESERVED_KEYS = new Set(['__proto__', 'constructor', 'prototype']);

/** IDs are generated by newId(); they're used as object keys, so reserved names are rejected. */
export function isSafeId(v: unknown): v is string {
  return typeof v === 'string' && ID_PATTERN.test(v) && !RESERVED_KEYS.has(v);
}

function sanitizeTask(raw: unknown, now: number): Task | null {
  if (!raw || typeof raw !== 'object') return null;
  const t = raw as Record<string, unknown>;
  if (!isSafeId(t.id)) return null;
  return {
    id: t.id,
    text: str(t.text, '', MAX_TASK_LENGTH),
    done: t.done === true,
    createdAt: num(t.createdAt, now),
    updatedAt: num(t.updatedAt, now),
  };
}

/** Field-by-field validation; unknown fields are dropped. */
function sanitizeNote(id: string, raw: unknown, now: number): Note | null {
  if (!raw || typeof raw !== 'object' || !isSafeId(id)) return null;
  const n = raw as Record<string, unknown>;
  const tasks = (Array.isArray(n.tasks) ? n.tasks : [])
    .map((t) => sanitizeTask(t, now))
    .filter((t): t is Task => t !== null);
  return {
    id,
    kind: n.kind === 'global' ? 'global' : 'tab',
    title: str(n.title, 'Tab note', MAX_TITLE_LENGTH),
    originalUrl: str(n.originalUrl, '', MAX_URL_LENGTH),
    url: str(n.url, '', MAX_URL_LENGTH),
    tabId: numOrNull(n.tabId),
    windowId: numOrNull(n.windowId),
    tasks,
    status: n.status === 'archived' ? 'archived' : 'active',
    createdAt: num(n.createdAt, now),
    updatedAt: num(n.updatedAt, now),
    archivedAt: numOrNull(n.archivedAt),
    archiveReason: ARCHIVE_REASONS.includes(n.archiveReason as ArchiveReason) ? (n.archiveReason as ArchiveReason) : null,
    detachedAt: numOrNull(n.detachedAt),
  };
}

/** Repairs/normalizes anything loaded from storage. Never drops valid tasks. */
export function normalizeState(raw: unknown, now: number): AppState {
  if (!raw || typeof raw !== 'object') return createInitialState(now);
  const r = raw as Record<string, unknown>;
  const notes: Record<string, Note> = {};
  const rawNotes = r.notes && typeof r.notes === 'object' ? (r.notes as Record<string, unknown>) : {};
  for (const [id, n] of Object.entries(rawNotes)) {
    const note = sanitizeNote(id, n, now);
    if (note) notes[id] = note;
  }
  const global = notes[GLOBAL_NOTE_ID];
  notes[GLOBAL_NOTE_ID] = global
    ? { ...global, kind: 'global', title: 'Global', status: 'active', tabId: null, detachedAt: null }
    : createGlobalNote(now);
  const settings = (r.settings && typeof r.settings === 'object' ? r.settings : {}) as Record<string, unknown>;
  return {
    version: SCHEMA_VERSION,
    rev: num(r.rev, 0),
    notes,
    settings: { switchTabs: settings.switchTabs === true },
  };
}

// ---------------------------------------------------------------- helpers

function patchNote(state: AppState, noteId: string, fn: (n: Note) => Note): AppState {
  const note = state.notes[noteId];
  if (!note) return state;
  const next = fn(note);
  if (next === note) return state;
  return { ...state, notes: { ...state.notes, [noteId]: next } };
}

function patchTasks(state: AppState, noteId: string, now: number, fn: (tasks: Task[]) => Task[]): AppState {
  return patchNote(state, noteId, (n) => {
    const tasks = fn(n.tasks);
    return tasks === n.tasks ? n : { ...n, tasks, updatedAt: now };
  });
}

const clean = (text: string, max: number) => text.replace(/\s+/g, ' ').trim().slice(0, max);

export function isTabNote(n: Note): boolean {
  return n.kind === 'tab';
}

export function findNoteByTab(state: AppState, tabId: number): Note | undefined {
  return Object.values(state.notes).find(
    (n) => n.kind === 'tab' && n.status === 'active' && n.tabId === tabId,
  );
}

/** Global first, then attached tab notes in creation order. */
export function navigableNotes(state: AppState): Note[] {
  const tabNotes = Object.values(state.notes)
    .filter((n) => n.kind === 'tab' && n.status === 'active' && n.detachedAt === null)
    .sort((a, b) => a.createdAt - b.createdAt);
  return [state.notes[GLOBAL_NOTE_ID], ...tabNotes].filter(Boolean);
}

export function archivedNotes(state: AppState): Note[] {
  return Object.values(state.notes)
    .filter((n) => n.status === 'archived')
    .sort((a, b) => (b.archivedAt ?? 0) - (a.archivedAt ?? 0));
}

// ---------------------------------------------------------------- user ops

export type Op =
  | { t: 'task.add'; noteId: string; taskId: string; text: string; index?: number }
  | { t: 'task.update'; noteId: string; taskId: string; text?: string; done?: boolean }
  | { t: 'task.delete'; noteId: string; taskId: string }
  | { t: 'task.move'; noteId: string; taskId: string; toIndex: number }
  | { t: 'note.clearCompleted'; noteId: string }
  | { t: 'note.rename'; noteId: string; title: string }
  | { t: 'note.delete'; noteId: string }
  | { t: 'settings.set'; patch: Partial<Settings> };

export function applyOp(state: AppState, op: Op, now: number): AppState {
  switch (op.t) {
    case 'task.add': {
      const text = clean(op.text, MAX_TASK_LENGTH);
      if (!text) return state;
      return patchTasks(state, op.noteId, now, (tasks) => {
        if (tasks.some((t) => t.id === op.taskId)) return tasks;
        const task: Task = { id: op.taskId, text, done: false, createdAt: now, updatedAt: now };
        const next = [...tasks];
        const i = op.index ?? next.length;
        next.splice(Math.max(0, Math.min(i, next.length)), 0, task);
        return next;
      });
    }
    case 'task.update':
      return patchTasks(state, op.noteId, now, (tasks) => {
        let changed = false;
        const next = tasks.map((t) => {
          if (t.id !== op.taskId) return t;
          const text = op.text === undefined ? t.text : clean(op.text, MAX_TASK_LENGTH) || t.text;
          const done = op.done ?? t.done;
          if (text === t.text && done === t.done) return t;
          changed = true;
          return { ...t, text, done, updatedAt: now };
        });
        return changed ? next : tasks;
      });
    case 'task.delete':
      return patchTasks(state, op.noteId, now, (tasks) =>
        tasks.some((t) => t.id === op.taskId) ? tasks.filter((t) => t.id !== op.taskId) : tasks,
      );
    case 'task.move':
      return patchTasks(state, op.noteId, now, (tasks) => {
        const from = tasks.findIndex((t) => t.id === op.taskId);
        if (from < 0) return tasks;
        const to = Math.max(0, Math.min(op.toIndex, tasks.length - 1));
        if (from === to) return tasks;
        const next = [...tasks];
        const [task] = next.splice(from, 1);
        next.splice(to, 0, task);
        return next;
      });
    case 'note.clearCompleted':
      return patchTasks(state, op.noteId, now, (tasks) =>
        tasks.some((t) => t.done) ? tasks.filter((t) => !t.done) : tasks,
      );
    case 'note.rename': {
      const title = clean(op.title, MAX_TITLE_LENGTH);
      if (!title || op.noteId === GLOBAL_NOTE_ID) return state;
      return patchNote(state, op.noteId, (n) => (n.title === title ? n : { ...n, title, updatedAt: now }));
    }
    case 'note.delete': {
      // Only archived notes can be deleted; active notes and Global are protected.
      const note = state.notes[op.noteId];
      if (!note || note.kind === 'global' || note.status !== 'archived') return state;
      const notes = { ...state.notes };
      delete notes[op.noteId];
      return { ...state, notes };
    }
    case 'settings.set':
      return { ...state, settings: { ...state.settings, ...op.patch } };
  }
}

// ---------------------------------------------------------------- lifecycle

export interface TabNoteInput {
  noteId: string;
  tabId: number;
  windowId: number;
  url: string;
  title: string;
}

/** Creates a note for the tab, or returns state unchanged if one exists. */
export function createTabNote(state: AppState, input: TabNoteInput, now: number): AppState {
  if (findNoteByTab(state, input.tabId)) return state;
  const note: Note = {
    ...createGlobalNote(now),
    id: input.noteId,
    kind: 'tab',
    title: clean(input.title, MAX_TITLE_LENGTH) || 'Tab note',
    originalUrl: input.url,
    url: input.url,
    tabId: input.tabId,
    windowId: input.windowId,
  };
  return { ...state, notes: { ...state.notes, [note.id]: note } };
}

export function archiveNote(state: AppState, noteId: string, reason: ArchiveReason, now: number): AppState {
  return patchNote(state, noteId, (n) =>
    n.kind !== 'tab' || n.status === 'archived'
      ? n
      : { ...n, status: 'archived', archiveReason: reason, archivedAt: now, tabId: null, detachedAt: null },
  );
}

/** Tab closed. Window-closing closes are deferred since the browser may be quitting. */
export function handleTabRemoved(
  state: AppState,
  tabId: number,
  isWindowClosing: boolean,
  now: number,
): AppState {
  const note = findNoteByTab(state, tabId);
  if (!note) return state;
  if (isWindowClosing) {
    return patchNote(state, note.id, (n) => (n.detachedAt !== null ? n : { ...n, detachedAt: now }));
  }
  return archiveNote(state, note.id, 'tab-closed', now);
}

/** A window closed while the browser keeps running: its detached notes are archived. */
export function archiveDetachedInWindow(state: AppState, windowId: number, now: number): AppState {
  let next = state;
  for (const n of Object.values(state.notes)) {
    if (n.kind === 'tab' && n.status === 'active' && n.detachedAt !== null && n.windowId === windowId) {
      next = archiveNote(next, n.id, 'window-closed', now);
    }
  }
  return next;
}

/** Tab discarding/prerendering swaps tab IDs; keep the note bound. */
export function handleTabReplaced(state: AppState, addedTabId: number, removedTabId: number): AppState {
  const note = findNoteByTab(state, removedTabId);
  if (!note) return state;
  return patchNote(state, note.id, (n) => ({ ...n, tabId: addedTabId }));
}

export function handleTabUrl(state: AppState, tabId: number, url: string, windowId?: number): AppState {
  const note = findNoteByTab(state, tabId);
  if (!note) return state;
  return patchNote(state, note.id, (n) =>
    n.url === url && (windowId === undefined || n.windowId === windowId)
      ? n
      : { ...n, url, windowId: windowId ?? n.windowId },
  );
}

export function handleTabAttached(state: AppState, tabId: number, windowId: number): AppState {
  const note = findNoteByTab(state, tabId);
  if (!note || note.windowId === windowId) return state;
  return patchNote(state, note.id, (n) => ({ ...n, windowId }));
}

function bind(state: AppState, noteId: string, tab: TabInfo, now: number): AppState {
  return patchNote(state, noteId, (n) => ({
    ...n,
    status: 'active',
    tabId: tab.id,
    windowId: tab.windowId,
    url: tab.url || n.url,
    detachedAt: null,
    archivedAt: null,
    archiveReason: null,
    updatedAt: now,
  }));
}

/** Reconnects an archived note to a freshly opened tab. */
export function restoreNote(state: AppState, noteId: string, tab: TabInfo, now: number): AppState {
  const note = state.notes[noteId];
  if (!note || note.kind !== 'tab' || note.status !== 'archived') return state;
  if (findNoteByTab(state, tab.id)) return state;
  return bind(state, noteId, tab, now);
}

/** A tab appeared or navigated: reattach a detached note with the same URL. */
export function attachDetachedByUrl(state: AppState, tab: TabInfo, now: number): AppState {
  if (!tab.url || findNoteByTab(state, tab.id)) return state;
  const target = normalizeUrl(tab.url);
  const match = Object.values(state.notes)
    .filter((n) => n.kind === 'tab' && n.status === 'active' && n.detachedAt !== null)
    .sort((a, b) => a.createdAt - b.createdAt)
    .find((n) => normalizeUrl(n.url) === target);
  return match ? bind(state, match.id, tab, now) : state;
}

/** Archives detached notes whose grace period expired without a matching tab. */
export function sweepDetached(state: AppState, now: number, graceMs = DETACH_GRACE_MS): AppState {
  let next = state;
  for (const n of Object.values(state.notes)) {
    if (n.kind === 'tab' && n.status === 'active' && n.detachedAt !== null && now - n.detachedAt >= graceMs) {
      next = archiveNote(next, n.id, 'session-lost', now);
    }
  }
  return next;
}

/**
 * Re-binds active notes to currently open tabs.
 *
 * `newSession` is true after a browser restart (tab IDs are no longer
 * meaningful), so notes are matched by URL only; unmatched notes are detached
 * with a fresh grace period because session restore may still be opening tabs.
 * Otherwise a note whose tab is missing was closed while we weren't watching.
 */
export function reconcile(state: AppState, tabs: TabInfo[], newSession: boolean, now: number): AppState {
  const candidates = Object.values(state.notes)
    .filter((n) => n.kind === 'tab' && n.status === 'active')
    .sort((a, b) => a.createdAt - b.createdAt);
  const byId = new Map(tabs.map((t) => [t.id, t]));
  const claimed = new Set<number>();
  const bound = new Set<string>();
  let next = state;

  const claim = (n: Note, t: TabInfo) => {
    claimed.add(t.id);
    bound.add(n.id);
    const same = n.tabId === t.id && n.windowId === t.windowId && n.url === t.url && n.detachedAt === null;
    if (!same) next = bind(next, n.id, t, now);
  };

  // 1. Same tab ID and same URL: certainly the same tab.
  for (const n of candidates) {
    const t = n.tabId !== null ? byId.get(n.tabId) : undefined;
    if (t && !claimed.has(t.id) && normalizeUrl(t.url) === normalizeUrl(n.url)) claim(n, t);
  }
  // 2. Same session: an attached note keeps its tab even if the URL changed.
  if (!newSession) {
    for (const n of candidates) {
      if (bound.has(n.id) || n.detachedAt !== null || n.tabId === null) continue;
      const t = byId.get(n.tabId);
      if (t && !claimed.has(t.id)) claim(n, t);
    }
  }
  // 3. Match remaining notes by URL (session restore).
  for (const n of candidates) {
    if (bound.has(n.id)) continue;
    const target = normalizeUrl(n.url);
    const t = tabs.find((x) => !claimed.has(x.id) && normalizeUrl(x.url) === target);
    if (t) claim(n, t);
  }
  // 4. Unmatched notes.
  for (const n of candidates) {
    if (bound.has(n.id)) continue;
    if (newSession) {
      next = patchNote(next, n.id, (x) => ({ ...x, tabId: null, detachedAt: now }));
    } else if (n.detachedAt === null) {
      next = archiveNote(next, n.id, 'tab-closed', now);
    }
  }
  return next;
}
